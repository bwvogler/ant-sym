#!/usr/bin/env bash
# Tests for guard.sh and stop-check.sh, with sample hook input and a throwaway git repo. No network.
#   .claude/skills/reviewing-prs/scripts/test.sh
set -u
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
pass=0 fail=0
check() { # name, expected, actual
  if [ "$2" = "$3" ]; then pass=$((pass + 1)); else fail=$((fail + 1)); printf 'FAIL %s: expected %s, got %s\n' "$1" "$2" "$3"; fi
}

F=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'

# --- guard.sh -----------------------------------------------------------------------------------------
guard() { # tool, tool_input json -> deny | ask | allow
  out=$(jq -n --arg t "$1" --argjson i "$2" '{tool_name: $t, tool_input: $i}' | "$here/guard.sh")
  d=$(jq -r '.hookSpecificOutput.permissionDecision // empty' <<<"$out" 2>/dev/null)
  echo "${d:-allow}"
}
body() { jq -n --arg b "$1" '{body: $b}'; }
bash_() { jq -n --arg c "$1" '{command: $c}'; }
review() { jq -n --arg m "$1" --arg e "$2" --arg b "$3" '{method: $m, body: $b} + (if $e == "" then {} else {event: $e} end)'; }

check "comment with footer" allow "$(guard mcp__github__add_issue_comment "$(body "Looks good.$F")")"
check "comment without footer" deny "$(guard mcp__github__add_issue_comment "$(body "Looks good.")")"
check "comment naming a model" deny "$(guard mcp__github__add_issue_comment "$(body "Reviewed with Opus 5.5.$F")")"
check "comment naming a model id" deny "$(guard mcp__github__update_issue_comment "$(body "claude-sonnet-5-5 says$F")")"
check "reply needs the footer" deny "$(guard mcp__github__add_reply_to_pull_request_comment "$(body "Fixed.")")"
check "game words are not model names" allow "$(guard mcp__github__add_issue_comment "$(body "The opus of 5 ants; a fable.$F")")"
check "inline comment needs no footer" allow "$(guard mcp__github__add_comment_to_pending_review "$(body "N2. Stale.")")"
check "inline comment naming a model" deny "$(guard mcp__github__add_comment_to_pending_review "$(body "Haiku 5 thinks so")")"
check "pending review opens freely" allow "$(guard mcp__github__pull_request_review_write "$(review create "" "")")"
check "submit with footer" allow "$(guard mcp__github__pull_request_review_write "$(review submit_pending COMMENT "## Review$F")")"
check "submit without footer" deny "$(guard mcp__github__pull_request_review_write "$(review submit_pending COMMENT "## Review")")"
check "submit as APPROVE" deny "$(guard mcp__github__pull_request_review_write "$(review submit_pending APPROVE "## Review$F")")"
check "create with REQUEST_CHANGES" deny "$(guard mcp__github__pull_request_review_write "$(review create REQUEST_CHANGES "x$F")")"
check "create and submit at once needs footer" deny "$(guard mcp__github__pull_request_review_write "$(review create COMMENT "x")")"
check "resolve a thread" allow "$(guard mcp__github__pull_request_review_write '{"method":"resolve_thread","threadId":"PRRT_x"}')"
check "merge asks" ask "$(guard mcp__github__merge_pull_request '{"pullNumber":5}')"
check "other tools pass" allow "$(guard Read '{"file_path":"/x"}')"

check "worktree: guarded var" allow "$(guard Bash "$(bash_ 'W="${S:?}/pr57"; git worktree add --detach "$W" refs/pr/57')")"
check "worktree: guarded inline" allow "$(guard Bash "$(bash_ 'git worktree add --detach "${S:?}/pr57" refs/pr/57')")"
check "worktree: absolute" allow "$(guard Bash "$(bash_ 'git worktree add --detach /tmp/scratch/pr57 HEAD')")"
check "worktree: -C and -b" allow "$(guard Bash "$(bash_ 'git -C /repo worktree add -b try /tmp/s/m57 origin/main')")"
check "worktree: unguarded var" deny "$(guard Bash "$(bash_ 'git worktree add --detach "$S/r53m" refs/pr/53')")"
check "worktree: unguarded via W" deny "$(guard Bash "$(bash_ 'W="$S/r53m"; git worktree add --detach "$W" refs/pr/53')")"
check "worktree: right under /" deny "$(guard Bash "$(bash_ 'git worktree add --detach /r53m refs/pr/53')")"
check "worktree: relative" deny "$(guard Bash "$(bash_ 'git worktree add ../pr57 refs/pr/57')")"
check "worktree list is fine" allow "$(guard Bash "$(bash_ 'git worktree list')")"

check "fast tests pass" allow "$(guard Bash "$(bash_ 'cd web && env -u JEV_API_KEY npm test')")"
check "one seed passes" allow "$(guard Bash "$(bash_ 'env -u JEV_API_KEY npm run exp -- raidFind --seeds 1')")"
check "test:slow asks" ask "$(guard Bash "$(bash_ 'npm run test:slow')")"
check "seed sweep asks" ask "$(guard Bash "$(bash_ 'npm run exp -- game --seeds 1-20')")"
check "all assays ask" ask "$(guard Bash "$(bash_ 'npm run exp -- all --seeds 1')")"
check "side-bench asks" ask "$(guard Bash "$(bash_ 'node scripts/side-bench.mjs')")"
check "colony-cost --side asks" ask "$(guard Bash "$(bash_ 'node scripts/colony-cost.mjs -- --side')")"
check "colony-cost top-down passes" allow "$(guard Bash "$(bash_ 'node scripts/colony-cost.mjs')")"
check "live run asks" ask "$(guard Bash "$(bash_ 'node scripts/colony-live.mjs all --budget 0.10')")"
check "precache import passes" allow "$(guard Bash "$(bash_ 'node scripts/precache.mjs --import experiments/caches/a.json')")"
check "precache live asks" ask "$(guard Bash "$(bash_ 'node scripts/precache.mjs')")"

# Every slow / paid rule, and the review #58 cases (S1, S3, N1, N4, N5).
check "merge with auto-merge asks" ask "$(guard mcp__github__enable_pr_auto_merge '{"pullNumber":5}')"
check "node --test on slow/ asks" ask "$(guard Bash "$(bash_ 'cd web && node --test src/colony/tests/slow/economy.test.ts')")"
check "reading a slow test passes" allow "$(guard Bash "$(bash_ 'grep -n seed web/src/colony/tests/slow/economy.test.ts')")"
check "goldens diffstat passes" allow "$(guard Bash "$(bash_ 'git diff --stat HEAD -- web/src/colony/tests/slow/golden.json')")"
check "exp with default seeds asks" ask "$(guard Bash "$(bash_ 'env -u JEV_API_KEY npm run exp -- raidFind')")"
check "exp with a seed list asks" ask "$(guard Bash "$(bash_ 'npm run exp -- raidFind --seeds 1,2,3')")"
check "experiment.mjs one seed passes" allow "$(guard Bash "$(bash_ 'node scripts/experiment.mjs pass --seeds=3 --seconds 60')")"
for s in side-bench colony-bench economy-bench floor-bench roomy-bench bakeoff progression crown raids muddle raid-food ablate; do
  check "$s asks" ask "$(guard Bash "$(bash_ "env -u JEV_API_KEY node scripts/$s.mjs")")"
done
check "npm run colony-bench asks" ask "$(guard Bash "$(bash_ 'npm run colony-bench')")"
check "reading a bench passes" allow "$(guard Bash "$(bash_ 'sed -n 1,20p scripts/crown.mjs')")"
check "probe asks" ask "$(guard Bash "$(bash_ 'node scripts/probe.mjs 20 100')")"
check "npm run colony-cost --side asks" ask "$(guard Bash "$(bash_ 'npm run colony-cost -- --side')")"
check "worktree: -b with nothing after it ends (no hang)" allow "$(guard Bash "$(bash_ 'git worktree add -b')")"
check "worktree: guarded chain" allow "$(guard Bash "$(bash_ 'S="${T:?}/scratch"; W="$S/pr57"; git worktree add --detach "$W" HEAD')")"
check "worktree: unguarded chain" deny "$(guard Bash "$(bash_ 'S="$T/scratch"; W="$S/pr57"; git worktree add --detach "$W" HEAD')")"

# --- stop-check.sh --------------------------------------------------------------------------------------
repo="$tmp/repo"
mkdir -p "$repo/.beads"
git -C "$repo" init -q
git -C "$repo" config user.email t@t && git -C "$repo" config user.name t
echo '{}' >"$repo/.beads/issues.jsonl" && git -C "$repo" add -A && git -C "$repo" commit -qm init
stop() { # stop_hook_active -> block | allow
  out=$(jq -n --arg c "$repo" --argjson a "$1" '{cwd: $c, stop_hook_active: $a}' | CLAUDE_PROJECT_DIR="$repo" "$here/stop-check.sh")
  [ "$(jq -r '.decision // empty' <<<"$out" 2>/dev/null)" = block ] && echo block || echo allow
}
check "clean tree stops" allow "$(stop false)"
git -C "$repo" worktree add -q --detach "$tmp/wt" HEAD
check "left worktree blocks" block "$(stop false)"
check "never twice in a row" allow "$(stop true)"
git -C "$repo" worktree remove --force "$tmp/wt"
echo '{"x":1}' >"$repo/.beads/issues.jsonl"
check "jsonl export blocks" block "$(stop false)"
git -C "$repo" checkout -q -- .beads/issues.jsonl
git -C "$repo" worktree add -q -b side "$tmp/wt2" HEAD
check "a named-branch worktree is not ours" allow "$(stop false)"
git -C "$repo" worktree remove --force "$tmp/wt2"
git -C "$repo" checkout -q --detach
check "a detached main checkout is not a scratch worktree" allow "$(stop false)"

echo "reviewing-prs hooks: $pass passed, $fail failed"
[ "$fail" = 0 ]
