#!/usr/bin/env bash
# PreToolUse hook for the reviewing-prs skill (registered when the skill is invoked; it then stays on for
# the rest of the session, and in pr-reviewer agents). It enforces the skill's hard rules at the moment
# they would be broken, and stays silent otherwise:
#   GitHub posts   - a review body or PR comment must end with the Claude Code footer and name no model;
#                    a review is submitted as COMMENT, never APPROVE or REQUEST_CHANGES          -> deny
#   merging a PR   - only when the owner asked in this session                                    -> ask
#   git worktree add - the path must be absolute, not right under /, and an unguarded "$S/..." is
#                    refused (an empty $S once put a worktree at /r53m)                          -> deny
#   slow or paid runs - test:slow, sweeps (exp's default is 10 seeds), long game scripts, the
#                    benches, live Jev scripts; only when run, not when read                      -> ask
# Inline review comments (add_comment_to_pending_review) are checked for model names only: the footer
# goes on the review body. The deny reason says how to fix the call, so it reads as guidance.
# Fails open: without jq or readable input it allows the call rather than wedge the session.
# Portable: bash 3.2 and BSD tools (macOS) as well as GNU.
set -u

input=$(cat) || exit 0
command -v jq >/dev/null 2>&1 || exit 0
tool=$(jq -r '.tool_name // empty' <<<"$input" 2>/dev/null) || exit 0
[ -n "$tool" ] || exit 0

FOOTER='_Generated by [Claude Code](https://claude.ai/code)_'
MODEL_RE='claude-(opus|sonnet|haiku|fable)-[0-9]|(^|[^A-Za-z])(Opus|Sonnet|Haiku|Fable) [0-9]'

decide() { # decision, reason
  jq -n --arg d "$1" --arg r "$2" \
    '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: $d, permissionDecisionReason: $r}}'
  exit 0
}
field() { jq -r ".tool_input.$1 // empty" <<<"$input" 2>/dev/null; }

# check_body <body> <needs footer: 1|0> <what>
check_body() {
  if printf '%s' "$1" | grep -Eq "$MODEL_RE"; then
    decide deny "reviewing-prs: this $3 names a model. Nothing posted to GitHub names the model or its id; take it out and post again."
  fi
  if [ "$2" = 1 ] && ! printf '%s' "$1" | grep -Fq "$FOOTER"; then
    decide deny "reviewing-prs: this $3 has no footer. Every GitHub post ends with these lines, verbatim:

---
$FOOTER"
  fi
}

case "$tool" in
  mcp__github__add_issue_comment | mcp__github__update_issue_comment | mcp__github__add_reply_to_pull_request_comment)
    check_body "$(field body)" 1 "PR comment" ;;

  mcp__github__add_comment_to_pending_review)
    check_body "$(field body)" 0 "inline comment" ;;

  mcp__github__pull_request_review_write)
    method=$(field method) event=$(field event)
    case "$event" in APPROVE | REQUEST_CHANGES)
      decide deny "reviewing-prs: submit the review with event COMMENT. The verdict ('Approve', 'Changes requested') goes on the body's first line; it is the owner's repo and they decide. (Refused: event $event)" ;;
    esac
    case "$method" in
      submit_pending) check_body "$(field body)" 1 "review" ;;
      create) [ -n "$event" ] && check_body "$(field body)" 1 "review" ;;
    esac ;;

  mcp__github__merge_pull_request | mcp__github__enable_pr_auto_merge)
    decide ask "reviewing-prs: a reviewer merges only when the owner asked in this session. Approve only if you asked for this merge." ;;

  Bash)
    cmd=$(field command)
    [ -n "$cmd" ] || exit 0

    # git worktree add <path>: the path is the first argument that is not an option (or an option's value).
    if printf '%s' "$cmd" | grep -Eq 'git( -C [^ ]+)? worktree add'; then
      rest=$(printf '%s' "$cmd" | sed -E 's/.*git( -C [^ ]+)? worktree add//')
      path=""
      set -f; set -- $rest; set +f
      while [ $# -gt 0 ]; do
        case "$1" in
          -b | -B | --reason) shift; [ $# -gt 0 ] && shift ;;   # the option's value, if any
          -*) shift ;;
          *) path=$1; break ;;
        esac
      done
      path=${path#\"}; path=${path%\"}; path=${path#\'}; path=${path%\'}; path=${path%%;*}
      bad=""
      case "$path" in
        "") ;;
        '${'*':?'*'}'*) ;;                                  # ${S:?}/x: aborts if S is empty
        '$'[A-Za-z_]*/* | '${'[A-Za-z_]*'}/'*) bad="it starts with an unguarded variable; write \"\${S:?}/...\" so an empty S aborts" ;;
        '$'[A-Za-z_]* | '${'[A-Za-z_]*'}') ;;               # "$W", set (guarded) beforehand
        /*/*) ;;
        /*) bad="it sits right under / (an empty variable does that: /r53m)" ;;
        *) bad="it is relative; use an absolute path under the scratchpad" ;;
      esac
      # W="$S/pr57" in the same command hides the same fault behind "$W". Fine when S itself was set
      # from a guarded value in the same command (S="${T:?}/x"; W="$S/pr57").
      if [ -z "$bad" ]; then
        for v in $(printf '%s' "$cmd" | grep -oE '[A-Za-z_][A-Za-z_0-9]*="?(\$[A-Za-z_][A-Za-z_0-9]*|\$\{[A-Za-z_][A-Za-z_0-9]*\})/' |
          sed -E 's/.*=\"?\$\{?([A-Za-z_][A-Za-z_0-9]*)\}?\/$/\1/'); do
          printf '%s' "$cmd" | grep -Eq "(^|[;&| ])$v=\"?\\\$\{[A-Za-z_][A-Za-z_0-9]*:\?" && continue
          bad="a path variable is set from an unguarded one (X=\"\$$v/...\"); write X=\"\${$v:?}/...\""
          break
        done
      fi
      [ -n "$bad" ] && decide deny "reviewing-prs: worktree path '$path' refused: $bad. Example: W=\"\${S:?}/pr57\"; git worktree add --detach \"\$W\" refs/pr/57"
    fi

    # Slow or paid runs, only when run (node / npm run), not when a file is read or grepped. Option A
    # (owner, 2026-11-09): a list of the slow scripts, extended as scripts are added.
    run='(node|npm run|npx)[^;|&]*'
    on() { printf '%s' "$cmd" | grep -Eq "$1"; }
    slow=""
    on 'npm run test:slow|node --test[^;|&]*tests/slow/' && slow="the slow test suite"
    exp=$(printf '%s' "$cmd" | grep -oE '(npm run exp|node [^;|&]*experiment\.mjs)[^;|&]*' | head -1)
    if [ -n "$exp" ]; then
      if printf '%s' "$exp" | grep -Eq '(--|experiment\.mjs) +all( |$)'; then slow="every assay"
      elif ! printf '%s' "$exp" | grep -Eq -- '--seeds[ =]+[0-9]+( |$)'; then
        slow="a multi-seed sweep (npm run exp runs seeds 1-10 unless given one seed: --seeds 1)"
      fi
    fi
    on "$run"'((side|colony|economy|floor|roomy)-bench|bakeoff|progression|crown|raids|muddle|raid-food|ablate)(\.mjs)?( |$)' && slow="a bench or long game run"
    on "$run"'colony-cost(\.mjs)?[^;|&]*--side' && slow="colony-cost --side"
    on "$run"'(colony-live|probe)\.mjs' && slow="a live Jev run (spends money)"
    pre=$(printf '%s' "$cmd" | grep -oE "$run"'precache\.mjs[^;|&]*' | head -1)
    if [ -n "$pre" ] && ! printf '%s' "$pre" | grep -q -- '--import'; then
      slow="precache.mjs without --import (asks Jev live, spends money)"
    fi
    [ -n "$slow" ] && decide ask "reviewing-prs: $slow. Reviews skip slow and paid runs unless the owner asked; list it under 'Not re-measured (slow)' instead. Approve only if you asked for it."
    ;;
esac
exit 0
